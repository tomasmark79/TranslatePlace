export function targetLanguage(settings, secondary = false) {
    const key = secondary ? "secondary-target-language" : "target-language";
    // Preserve the output language selected by older versions.
    const legacy = !secondary && settings.get_user_value(key) === null &&
        settings.get_string("direction") === "en-cs";
    const code = legacy ? "cs" : settings.get_string(key);
    return LANGUAGES.some(([value]) => value === code) ? code : (secondary ? "cs" : "en");
}
